/* 역명 표기 정규화 */
const normalizeStation = (s) => (s ? s.replace(/駅$/, "") : s);

// (route, station) → 고유 키
const pairKey = (route, st) => `${route}@@${st}`;
const splitKey = (key) => {
  const i = key.indexOf("@@");
  return [key.slice(0, i), key.slice(i + 2)];
};

